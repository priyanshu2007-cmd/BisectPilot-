"""Generate config/repository-manifest.json, config/skill-index.json and MANIFEST.md from what is actually on disk."""
import json, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from skilllib import parse_frontmatter, categorize

root = Path(sys.argv[1]).resolve()
sources = json.loads((root / "config/sources.json").read_text())

def rel(p): return p.relative_to(root).as_posix()

# ---- skill index -----------------------------------------------------------
skills = []
def add(p, source):
    fm = parse_frontmatter(p)
    d = p.parent
    name = fm.get("name") or d.name
    desc = fm.get("description", "")
    for i, old in enumerate(skills):  # same id twice: keep one, prefer the generated copy
        if old["id"] == f"{source}:{name}":
            if "generated" in p.parts and "generated" not in Path(old["path"]).parts:
                skills.pop(i); break
            return
    skills.append({"id": f"{source}:{name}", "name": name, "description": desc[:600],
                   "path": rel(p), "source": source, "license": fm.get("license", ""),
                   "categories": categorize(f"{name} {desc}"), "frontmatter_ok": bool(fm.get("name") and fm.get("description"))})
for p in sorted((root / "skills").glob("*/SKILL.md")): add(p, "toolkit")
for s in sources:
    base = root / "repositories" / s["category"] / s["name"]
    if (base / ".source.json").exists():
        for p in sorted(base.rglob("SKILL.md")): add(p, s["name"])
(root / "config/skill-index.json").write_text(json.dumps({"schema": 1, "count": len(skills), "skills": skills}, indent=1) + "\n")

# ---- repository manifest ---------------------------------------------------
entries = []
for s in sources:
    base = root / "repositories" / s["category"] / s["name"]
    sj = base / ".source.json"
    info = json.loads(sj.read_text()) if sj.exists() else {}
    has_lic = any(base.glob("LICEN[SC]E*")) or any(base.glob("COPYING*"))
    n_skills = sum(1 for k in skills if k["source"] == s["name"])
    if not sj.exists(): status = "not-retrieved"
    elif info.get("mode") == "pointer": status = "pointer-only"
    else: status = "retrieved"
    e = dict(s)
    e.update({"local_path": rel(base) if sj.exists() else None, "commit": info.get("commit"),
              "fetched_at": info.get("fetched_at"), "license_file_retained": has_lic,
              "license_verified": has_lic or bool(s.get("license_verification")), "installation_status": status, "skills_indexed": n_skills,
              "supported_agents_note": "listed agents are those with a native adapter dir in the upstream repo; others unverified" if s["agents_verified"] else "unverified"})
    entries.append(e)
(root / "config/repository-manifest.json").write_text(json.dumps({"schema": 1, "repositories": entries}, indent=1) + "\n")

# ---- MANIFEST.md (kept short on purpose: it is read at the start of tasks) --
mine = [k for k in skills if k["source"] == "toolkit"]
counts = {}
for k in skills: counts[k["source"]] = counts.get(k["source"], 0) + 1
ret = sum(e["installation_status"] == "retrieved" for e in entries)
ptr = sum(e["installation_status"] == "pointer-only" for e in entries)
L = ["# MANIFEST (generated by scripts/lib/build_config.py; do not edit)", "",
     "Toolkit root = the folder containing this file. All paths below are relative to it.", "",
     "## How to use", "1. Find skills: `scripts/skill-search.sh \"<task words>\"` (top 3 by default).",
     "2. Read only the returned `SKILL.md` (1-3 files). Do NOT read every skill or repository.",
     "3. Full data: `config/skill-index.json` (skills), `config/repository-manifest.json` (sources, licenses, status).", "",
     f"## Toolkit skills ({len(mine)})"]
L += [f"- `{k['path']}` — {k['description'][:110]}" for k in mine]
L += ["", f"## Indexed third-party skills: {len(skills) - len(mine)} from {len(counts) - (1 if 'toolkit' in counts else 0)} repositories",
      ", ".join(f"{n}:{c}" for n, c in sorted(counts.items()) if n != "toolkit"), "",
      f"## Repositories: {len(entries)} total, {ret} retrieved, {ptr} pointer-only, {len(entries)-ret-ptr} not retrieved",
      "Pointer-only repos (license or size) are listed in `config/repository-manifest.json` with URL and install method."]
(root / "MANIFEST.md").write_text("\n".join(L) + "\n")
print(f"[info] skills indexed: {len(skills)} | repos retrieved: {ret}, pointer-only: {ptr}, other: {len(entries)-ret-ptr}", file=sys.stderr)
